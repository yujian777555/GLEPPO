"""PC1 myopia-diagnostic protocol (zero-cost validation helpers).

R3: r_hat and Q_hat first step use the SAME frozen reward (gleppo.reward.generation_reward).
R4: explicit state_id / rollout_id / replicate_id; CRN paired seeds; cache never
    counts as a new sample.
R7: planned-slot vs actual-CTX accounting.

PC1 must NOT be executed until the second independent review approves this.
"""
from __future__ import annotations

import hashlib
from dataclasses import dataclass, field
from typing import Callable, Dict, List, Optional, Sequence, Tuple

from .reward import generation_reward, discounted_return, GAMMA

PROTOCOL_VERSION = "pc1-amendment-v2"

# ---- Pre-registered thresholds (UNCHANGED from Phase 1) ----
THRESHOLD_D = 0.15
THRESHOLD_ADVANTAGE = 0.02
MARGIN_D = 0.10
MARGIN_ADV = 0.01

# ---- Budget (R2: >=100 states; R7: init + collection included) ----
N_STATES = 100
N_ACTIONS = 5
Q_ROLLOUTS = 3          # rollouts for Q_hat per (s,a)
HORIZON = 3             # h=3 continuation
LAMBDA = 4
N_EVAL = 2              # PC1 replicas (main experiments use 3)
MU = 8
EXTRA_IMMEDIATE = 1     # extra draws for r_hat
N_STATE_COLLECTION_EPISODES = 40
T_COLLECT = 15

# Conservative planned-slot arithmetic (review §"Proposed amendment"):
#   Q rollouts:  100*5*3*(3 gens)*4*2 = 36,000
#   Extra r_hat: 100*5*1*1*4*2       =  4,000
#   State coll.: 40*(8*2 + 15*4*2)   =  5,440
#   Total = 45,440 planned slots <= 50,000 hard cap
PLANNED_Q_SLOTS = N_STATES * N_ACTIONS * Q_ROLLOUTS * HORIZON * LAMBDA * N_EVAL
PLANNED_EXTRA_SLOTS = N_STATES * N_ACTIONS * EXTRA_IMMEDIATE * LAMBDA * N_EVAL
PLANNED_COLLECTION_SLOTS = N_STATE_COLLECTION_EPISODES * (MU * N_EVAL + T_COLLECT * LAMBDA * N_EVAL)
PLANNED_TOTAL_SLOTS = PLANNED_Q_SLOTS + PLANNED_EXTRA_SLOTS + PLANNED_COLLECTION_SLOTS
HARD_CAP_SLOTS = 50000


def crn_seed(state_id: str, action: int, rollout_id: int) -> str:
    """R4: common random numbers across actions for the same (state, rollout).

    The SAME seed is used for different actions at the same (state_id, rollout_id)
    so that paired action comparisons share evaluation randomness, while distinct
    rollouts/replicates get distinct seeds.
    """
    return hashlib.sha256(f"CRN|{state_id}|{rollout_id}".encode("utf-8")).hexdigest()[:16]


def replicate_seed(state_id: str, action: int, rollout_id: int, rep: int) -> str:
    """Distinct Monte Carlo replicate seed (never reused across reps)."""
    return hashlib.sha256(
        f"REP|{state_id}|{action}|{rollout_id}|{rep}".encode("utf-8")
    ).hexdigest()[:16]


def myopic_reward_from_trace(gen_rewards: Sequence[float]) -> float:
    """r_hat component: the FIRST generation reward (same frozen function)."""
    return gen_rewards[0] if gen_rewards else 0.0


def q_hat_from_trace(gen_rewards: Sequence[float], gamma: float = GAMMA) -> float:
    """Q_hat = h-step discounted return under the fixed random continuation policy.

    The first reward term is generated by the SAME frozen generation_reward as r_hat.
    """
    return discounted_return(gen_rewards[:HORIZON], gamma=gamma)


@dataclass
class BudgetLedger:
    """R7: distinguishes planned slots, actual CTX, cache hits, invalids, LLM calls."""
    planned_slots: int = 0
    actual_ctx: int = 0
    cache_hits: int = 0
    invalid_offspring: int = 0
    valid_offspring: int = 0
    operator_llm_calls: int = 0
    agent_llm_turns: int = 0
    notes: List[str] = field(default_factory=list)

    def record_generation(self, lam: int, n_eval: int, valid: int, invalid: int,
                          cache_hits: int, op_llm_calls: int, agent_turns: int) -> None:
        self.planned_slots += lam * n_eval
        self.valid_offspring += valid
        self.invalid_offspring += invalid
        self.actual_ctx += valid * n_eval - cache_hits  # cache hits are not new CTX
        self.cache_hits += cache_hits
        self.operator_llm_calls += op_llm_calls
        self.agent_llm_turns += agent_turns

    def record_init(self, mu: int, n_eval: int, actual: int, cache_hits: int) -> None:
        self.planned_slots += mu * n_eval
        self.actual_ctx += max(0, actual - cache_hits)
        self.cache_hits += cache_hits

    def summary(self) -> dict:
        return {
            "planned_slots": self.planned_slots,
            "actual_ctx": self.actual_ctx,
            "cache_hits": self.cache_hits,
            "invalid_offspring": self.invalid_offspring,
            "valid_offspring": self.valid_offspring,
            "operator_llm_calls": self.operator_llm_calls,
            "agent_llm_turns": self.agent_llm_turns,
            "hard_cap_slots": HARD_CAP_SLOTS,
            "within_cap": self.planned_slots <= HARD_CAP_SLOTS,
        }


def zero_cost_protocol_check() -> dict:
    """Validate budget arithmetic, CRN/replicate seed properties, reward identity.

    Runs WITHOUT any model or environment execution. Returns a report dict.
    """
    checks: Dict[str, Tuple[bool, str]] = {}

    # R2/R7: budget
    checks["planned_within_hard_cap"] = (
        PLANNED_TOTAL_SLOTS <= HARD_CAP_SLOTS,
        f"planned={PLANNED_TOTAL_SLOTS} cap={HARD_CAP_SLOTS}",
    )
    checks["states_at_least_100"] = (N_STATES >= 100, f"n_states={N_STATES}")
    checks["init_slots_included"] = (
        PLANNED_COLLECTION_SLOTS >= N_STATE_COLLECTION_EPISODES * MU * N_EVAL,
        f"collection includes init: {PLANNED_COLLECTION_SLOTS}",
    )

    # R4: CRN property — same (state, rollout) => same seed across actions
    s1 = crn_seed("s0", 0, 0)
    s2 = crn_seed("s0", 3, 0)   # different action, same state+rollout
    checks["crn_shared_across_actions"] = (s1 == s2, f"{s1} == {s2}")
    s3 = crn_seed("s0", 0, 1)   # different rollout
    checks["crn_distinct_across_rollouts"] = (s1 != s3, f"{s1} != {s3}")

    # R4: replicate seeds distinct
    r1 = replicate_seed("s0", 0, 0, 0)
    r2 = replicate_seed("s0", 0, 0, 1)
    r3 = replicate_seed("s0", 1, 0, 0)
    checks["replicate_seeds_distinct"] = (len({r1, r2, r3}) == 3, f"{r1},{r2},{r3}")

    # R3: reward identity — generation_reward used by both estimators
    rew = [0.1, -0.2, 0.3]
    r_hat = myopic_reward_from_trace(rew)
    q_hat = q_hat_from_trace(rew)
    manual_q = rew[0] + GAMMA * rew[1] + (GAMMA ** 2) * rew[2]
    checks["reward_identity_first_term"] = (r_hat == rew[0], f"r_hat={r_hat}")
    checks["q_uses_same_first_term"] = (abs(q_hat - manual_q) < 1e-9, f"q={q_hat} manual={manual_q}")

    # reward function clipping
    big = generation_reward(10.0, 0.0, 10.0, 0.0, 1.0)
    neg = generation_reward(0.0, 10.0, 0.0, 10.0, 0.0)
    checks["reward_clip_hi"] = (big == 1.0, f"{big}")
    checks["reward_clip_lo"] = (neg == -0.5, f"{neg}")

    all_ok = all(ok for ok, _ in checks.values())
    return {
        "protocol_version": PROTOCOL_VERSION,
        "all_pass": all_ok,
        "checks": {k: {"ok": ok, "detail": d} for k, (ok, d) in checks.items()},
        "budget": {
            "q_slots": PLANNED_Q_SLOTS,
            "extra_slots": PLANNED_EXTRA_SLOTS,
            "collection_slots": PLANNED_COLLECTION_SLOTS,
            "total_planned": PLANNED_TOTAL_SLOTS,
            "hard_cap": HARD_CAP_SLOTS,
            "headroom": HARD_CAP_SLOTS - PLANNED_TOTAL_SLOTS,
        },
        "thresholds": {
            "D": THRESHOLD_D,
            "advantage": THRESHOLD_ADVANTAGE,
            "margin_D": MARGIN_D,
            "margin_advantage": MARGIN_ADV,
            "inconclusive_rule": "SR1 STOP",
        },
    }
